def _dispatch_email_alert(subject, body_text, to_email):
    """Dispatches real-time email notification using SMTP."""
    if not to_email:
        to_email = 'nishanthissan1515@gmail.com'

    settings = AlertSettings.query.first()
    smtp_host = settings.smtp_host if (settings and settings.smtp_host) else 'smtp.gmail.com'
    smtp_port = settings.smtp_port if (settings and settings.smtp_port) else 587
    smtp_user = settings.smtp_user if (settings and settings.smtp_user) else ''
    smtp_pass = settings.smtp_password if (settings and settings.smtp_password) else ''

    # If custom SMTP credentials are provided, send via SMTP server
    if smtp_user and smtp_pass:
        try:
            msg = MIMEMultipart('alternative')
            msg['Subject'] = subject
            msg['From'] = f"FlyAsh Alert <{smtp_user}>"
            msg['To'] = to_email

            html_content = f"""
            <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 20px; border: 1px solid #e2e8f0; border-radius: 8px; background-color: #ffffff;">
                <div style="background-color: #1e3a8a; padding: 15px; border-radius: 6px; text-align: center; color: #ffffff;">
                    <h2 style="margin: 0; font-size: 20px;">FlyAsh & Block Plant Management</h2>
                    <p style="margin: 4px 0 0 0; font-size: 13px; opacity: 0.9;">Security & Login Alert System</p>
                </div>
                <div style="padding: 20px 0; color: #334155; line-height: 1.6;">
                    <p style="font-size: 15px; font-weight: bold; color: #0f172a;">{subject}</p>
                    <div style="background-color: #f8fafc; border-left: 4px solid #3b82f6; padding: 15px; border-radius: 4px; margin: 15px 0;">
                        <pre style="font-family: inherit; margin: 0; white-space: pre-wrap; font-size: 14px;">{body_text}</pre>
                    </div>
                    <p style="font-size: 13px; color: #64748b; margin-top: 20px;">
                        This automated notification was generated by your FlyAsh Manager system running on your local server.
                    </p>
                </div>
            </div>
            """

            msg.attach(MIMEText(body_text, 'plain'))
            msg.attach(MIMEText(html_content, 'html'))

            with smtplib.SMTP(smtp_host, smtp_port, timeout=8) as server:
                server.starttls()
                server.login(smtp_user, smtp_pass)
                server.sendmail(smtp_user, [to_email], msg.as_string())
            print(f"[OK] Email alert successfully sent to {to_email}")
            return True, "Email sent successfully via SMTP!"
        except Exception as e:
            print(f"[WARN] SMTP Email delivery error: {e}")
            return False, f"SMTP Error: {str(e)}"
    
    # Fallback log notice when SMTP credentials are not configured yet
    print(f"[INFO] Email alert prepared for {to_email}")
    return True, f"Email notification queued for {to_email}. (Enter your Gmail App Password under Advanced SMTP to send live emails)"


def _dispatch_mobile_alert(message_text):
    """Dispatches real-time alert message to owner's mobile phone (WhatsApp/Telegram/SMS/Webhook)."""
    try:
        settings = AlertSettings.query.first()
        if not settings or not settings.is_enabled:
            return

        raw_phone = (settings.phone_number or '8072416903').replace('+', '').replace(' ', '').replace('-', '').strip()
        phone = ('91' + raw_phone) if len(raw_phone) == 10 else raw_phone

        if settings.channel in ['whatsapp', 'both'] and phone and settings.api_key:
            text_encoded = urllib.parse.quote(message_text)
            url = f"https://api.callmebot.com/whatsapp.php?phone={phone}&text={text_encoded}&apikey={settings.api_key}"
            requests.get(url, timeout=4)

        if settings.channel in ['telegram', 'both'] and settings.api_key and settings.chat_id:
            url = f"https://api.telegram.org/bot{settings.api_key}/sendMessage"
            payload = {'chat_id': settings.chat_id, 'text': message_text}
            requests.post(url, json=payload, timeout=4)

        if settings.channel == 'sms' and phone and settings.api_key:
            url = "https://www.fast2sms.com/dev/bulkV2"
            headers = {'authorization': settings.api_key}
            payload = {
                'route': 'q',
                'message': message_text,
                'language': 'english',
                'flash': 0,
                'numbers': raw_phone
            }
            requests.post(url, headers=headers, json=payload, timeout=4)

        if settings.channel == 'webhook' and settings.webhook_url:
            requests.post(settings.webhook_url, json={'phone': phone, 'alert': message_text, 'timestamp': datetime.now().isoformat()}, timeout=4)

    except Exception as e:
        print(f"[WARN] Error dispatching mobile alert: {e}")


def _send_login_alert(user, login_identifier, status, ip_address, user_agent):
    """Logs sign-in event, prints to console, and sends mobile + email alert to owner about the login user."""
    try:
        uname = user.username if user else (login_identifier or 'UNKNOWN')
        uemail = user.email if user else (login_identifier if '@' in (login_identifier or '') else '')
        urole = user.role if user else 'guest'
        uid = user.id if user else None

        log_entry = LoginHistory(
            user_id=uid,
            username=uname,
            email=uemail,
            user_role=urole,
            ip_address=ip_address,
            user_agent=user_agent[:250] if user_agent else '',
            status=status,
            timestamp=datetime.now()
        )
        db.session.add(log_entry)
        db.session.commit()

        time_str = datetime.now().strftime('%d-%b-%Y at %I:%M:%S %p')
        print(f"\n{'='*60}\n  [LOGIN ALERT] User: '{uname}' ({uemail}) | Role: {urole}\n  Status: {status} | Time: {time_str} | IP: {ip_address}\n{'='*60}\n")

        settings = AlertSettings.query.first()
        owner_email = settings.owner_email if (settings and settings.owner_email) else 'nishanthissan1515@gmail.com'

        # Construct alert content
        if status == 'SUCCESS':
            if user and (user.role == 'owner' or user.email == owner_email):
                subject = f"🔔 FlyAsh Manager: Owner Login Alert ({user.name or uname})"
                body = (f"Owner Sign-in Notification:\n\n"
                        f"• Account: {user.name or uname} ({uemail})\n"
                        f"• Role: {urole.capitalize()}\n"
                        f"• Time: {time_str}\n"
                        f"• IP Address: {ip_address}\n"
                        f"• Device: {user_agent or 'Standard Browser'}")
            else:
                display_name = user.name or user.username if user else uname
                subject = f"🚨 FlyAsh Manager: Staff Login Alert - {display_name} ({urole.capitalize()})"
                body = (f"Alert: A user / staff member has just logged in to your plant system:\n\n"
                        f"• User Name: {display_name}\n"
                        f"• Login Email: {uemail or uname}\n"
                        f"• Role / Permission: {urole.capitalize()}\n"
                        f"• Time of Login: {time_str}\n"
                        f"• IP Address: {ip_address}\n"
                        f"• Device / Browser: {user_agent or 'Standard Browser'}")
        elif status == 'WRONG_PASSWORD' and user:
            display_name = user.name or user.username
            subject = f"🚨 Security Alert: WRONG PASSWORD Attempt for '{display_name}'"
            body = (f"⚠️ SECURITY WARNING - WRONG PASSWORD ENTERED\n\n"
                    f"Someone attempted to log in with an INCORRECT PASSWORD to:\n"
                    f"• Target Account: {display_name} ({user.email or user.username})\n"
                    f"• Role / Permission: {urole.capitalize()}\n"
                    f"• Time of Attempt: {time_str}\n"
                    f"• IP Address: {ip_address}\n"
                    f"• Device / Browser: {user_agent or 'Standard Browser'}\n\n"
                    f"Notification dispatched to Owner ({owner_email} & 8072416903).")
        else:
            subject = f"⚠️ Security Alert: Failed Login Attempt ({login_identifier})"
            body = (f"⚠️ SECURITY WARNING - FAILED LOGIN ATTEMPT\n\n"
                    f"An unknown or failed login attempt was detected on your system:\n"
                    f"• Attempted Login ID: {login_identifier}\n"
                    f"• Time of Attempt: {time_str}\n"
                    f"• IP Address: {ip_address}\n"
                    f"• Device / Browser: {user_agent or 'Standard Browser'}\n\n"
                    f"Notification dispatched to Owner ({owner_email} & 8072416903).")

        # Smart Anti-Spam & Frequency Throttling Check
        should_dispatch = True
        skip_reason = ""

        if settings:
            is_owner = (user and (user.role == 'owner' or user.email == owner_email))

            if status == 'SUCCESS':
                # 1. Role Alert Filter
                if is_owner and not getattr(settings, 'alert_on_owner_login', False):
                    should_dispatch = False
                    skip_reason = "Owner login alerts are disabled in settings (no self-spam)"
                elif not is_owner and not getattr(settings, 'alert_on_staff_login', True):
                    should_dispatch = False
                    skip_reason = "Staff login alerts are turned off in settings"
                elif not getattr(settings, 'alert_on_all_users', True) and not is_owner:
                    should_dispatch = False
                    skip_reason = "Staff alerts are toggled off"

                # 2. Duplicate / Frequency Throttling per user
                if should_dispatch and uid:
                    today_start = datetime.now().replace(hour=0, minute=0, second=0, microsecond=0)

                    # First login of the day rule
                    if getattr(settings, 'alert_on_first_login_only', False):
                        earlier_today = LoginHistory.query.filter(
                            LoginHistory.user_id == uid,
                            LoginHistory.id != log_entry.id,
                            LoginHistory.status == 'SUCCESS',
                            LoginHistory.timestamp >= today_start
                        ).first()
                        if earlier_today:
                            should_dispatch = False
                            skip_reason = f"Alert already sent for user '{uname}' earlier today (First login of the day rule active)"

                    # Max alerts per user per day rule
                    max_day = getattr(settings, 'max_alerts_per_day', 3)
                    if should_dispatch and max_day > 0:
                        count_today = LoginHistory.query.filter(
                            LoginHistory.user_id == uid,
                            LoginHistory.status == 'SUCCESS',
                            LoginHistory.timestamp >= today_start
                        ).count()
                        if count_today > max_day:
                            should_dispatch = False
                            skip_reason = f"User '{uname}' reached daily alert cap of {max_day} notifications"

                    # Cooldown interval rule
                    cooldown = getattr(settings, 'cooldown_minutes', 30)
                    if should_dispatch and cooldown > 0:
                        prev_entry = LoginHistory.query.filter(
                            LoginHistory.user_id == uid,
                            LoginHistory.id != log_entry.id,
                            LoginHistory.status == 'SUCCESS'
                        ).order_by(LoginHistory.timestamp.desc()).first()
                        if prev_entry:
                            diff_mins = (datetime.now() - prev_entry.timestamp).total_seconds() / 60.0
                            if diff_mins < cooldown:
                                should_dispatch = False
                                skip_reason = f"Throttled: Last alert for '{uname}' was sent {int(diff_mins)}m ago (Cooldown: {cooldown}m)"

            elif status in ['WRONG_PASSWORD', 'USER_NOT_FOUND']:
                if not getattr(settings, 'alert_on_failed_attempts', True):
                    should_dispatch = False
                    skip_reason = "Failed attempt alerts disabled in settings"

        if not should_dispatch:
            print(f"  [ALERT THROTTLED] Message delivery skipped: {skip_reason}")
            return

        # 1. Dispatch Mobile Bot / WhatsApp / SMS to 8072416903
        if settings is None or settings.is_enabled:
            _dispatch_mobile_alert(body)

        # 2. Dispatch Direct Email to nishanthissan1515@gmail.com
        if settings is None or settings.email_alerts_enabled:
            _dispatch_email_alert(subject, body, owner_email)

    except Exception as e:
        db.session.rollback()
        print(f"[WARN] Error in _send_login_alert: {e}")


